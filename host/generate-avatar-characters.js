// Generate explicit Unicode ranges so ICU-less Android Node can validate avatars.
const fs=require('node:fs'),path=require('node:path');
const allowed=/^[\p{L}\p{N}\p{So}]$/u;
const ranges=[];
let start=-1;
const escape=point=>'\\u{'+point.toString(16)+'}';
for(let point=0;point<=0x110000;point++){
 const matches=point<0x110000&&allowed.test(String.fromCodePoint(point));
 if(matches&&start<0)start=point;
 if(!matches&&start>=0){ranges.push(escape(start)+(point-1===start?'':'-'+escape(point-1)));start=-1;}
}
const source='// Generated by host/generate-avatar-characters.js; Unicode '+process.versions.unicode+'.\n'+
 '(function(root){const pattern=new RegExp('+JSON.stringify('^['+ranges.join('')+']$')+',"u");const api={test:text=>pattern.test(text)};if(typeof module!=="undefined"&&module.exports)module.exports=api;else root.AvatarCharacters=api;})(globalThis);\n';
fs.writeFileSync(path.join(__dirname,'../public/avatar-characters.js'),source);
